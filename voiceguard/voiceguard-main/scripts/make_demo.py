"""Regenerate frontend/demo.js: the UI's scripted demo, scored by the real backend rules.

The lines and the voice scores are scripted; the scam scores, reasons and verdicts are
whatever the backend produces for them, so the demo can never show a state the server
would not send. Run it again after changing backend/scam_rules.py or backend/verdict.py:

    python scripts/make_demo.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from backend.config import Settings  # noqa: E402
from backend.pipeline import Analyzer  # noqa: E402
from backend.transcription import Transcript  # noqa: E402
from tests.helpers import tone  # noqa: E402

OUT = ROOT / "frontend" / "demo.js"

# (what is said in each 4 s window, scripted voice score for that window)
LINES = [
    ("Hello, is this Priya? I'm calling to confirm your delivery for tomorrow.", 0.03),
    ("Yes, that's right. Afternoon is fine, I'll be home all day.", 0.02),
    ("I'm calling from your bank about a payment. You need to act immediately.", 0.08),
    ("This is Inspector Sharma from the cyber police. Your ID is linked to an illegal parcel.", 0.71),
    ("You are under digital arrest. Stay on this video call and do not tell anyone.", 0.88),
    ("Read me the OTP on your phone and move your savings to our safe account right now.", 0.95),
]
KEEP = ("timestamp", "window_index", "transcript", "scam_score", "risk", "reasons", "voice_score", "voice_flag", "verdict")


class Script:
    """Stands in for both models: returns the scripted text and voice score, window by window."""

    def __init__(self):
        self.window = 0

    def transcribe(self, w, language=None):
        return Transcript(LINES[self.window][0], "en", 1.0)

    def score(self, w):
        value = LINES[self.window][1]
        self.window += 1
        return value

    def preload(self):
        pass

    def status(self):
        return {"state": "ready", "detail": "demo script", "error": None}


def main() -> int:
    script = Script()
    analyzer = Analyzer(Settings(preload_models=False), script, script, lambda w: 3.4)
    results, final = analyzer.analyze_clip(tone(4.0 * len(LINES)), "demo")
    demo = {
        "steps": [{k: v for k, v in r.model_dump().items() if k in KEEP} for r in results],
        "final": final.model_dump(),
    }
    OUT.write_text(
        "// Generated by scripts/make_demo.py from the backend's own rules. Do not edit by hand.\n"
        f"export const DEMO = {json.dumps(demo, indent=2, ensure_ascii=False)};\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)}: {len(demo['steps'])} steps, final verdict '{final.title}'")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
